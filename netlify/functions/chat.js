const SYSTEM_PROMPT = `당신은 그래픽팀 신규 입사자를 돕는 사내 프로세스 안내 챗봇입니다. 아래 지식베이스와 답변 규칙을 반드시 지켜서 사용자 질문에 답하세요.\n\n${KNOWLEDGE_BASE}`;

// "-latest" 별칭(예: gemini-flash-latest)은 구글이 이미 지원 종료해서 "Request contains an
// invalid argument" 오류를 냈다. 그래서 실제 존재하는 안정 버전 모델명을 직접 지정한다.
// 나중에 이 모델도 지원 종료되면, https://ai.google.dev/gemini-api/docs/models 에서
// "Free Tier: Free of charge"로 표시된 최신 Flash 계열 모델명으로 교체하면 된다.
const GEMINI_MODEL = "gemini-3.5-flash-lite"; // 응답 속도 개선을 위해 flash-lite로 변경 (2026-08-06)

exports.handler = async function (event) {
  if (event.httpMethod !== "POST") {
    return { statusCode: 405, body: JSON.stringify({ error: "Method Not Allowed" }) };
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return {
      statusCode: 500,
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ error: "서버에 GEMINI_API_KEY 환경변수가 설정되어 있지 않아요. Netlify 사이트 설정 > Environment variables에서 추가해 주세요." })
    };
  }

  let payload;
  try {
    payload = JSON.parse(event.body || "{}");
  } catch (e) {
    return { statusCode: 400, body: JSON.stringify({ error: "잘못된 요청 형식이에요." }) };
  }

  const { message, history, extraKnowledge } = payload;
  if (!message || typeof message !== "string") {
    return { statusCode: 400, body: JSON.stringify({ error: "message 값이 없어요." }) };
  }

  // admin.html(Supabase)에서 등록한 지식이 있으면 시스템 프롬프트에 덧붙인다.
  const systemPromptWithExtras =
    SYSTEM_PROMPT + (typeof extraKnowledge === "string" && extraKnowledge.trim() ? extraKnowledge : "");

  // Gemini API는 role을 "user" / "model"로 구분한다.
  const contents = [
    ...(Array.isArray(history) ? history : []).map(m => ({
      role: m.role === "user" ? "user" : "model",
      parts: [{ text: String(m.text || "") }]
    })),
    { role: "user", parts: [{ text: message }] }
  ];

  try {
    const geminiRes = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent?key=${apiKey}`,
      {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: systemPromptWithExtras }] },
          contents,
          // gemini-flash-latest가 가리키는 모델에 따라 thinkingBudget: 0을 거부하는 경우가 있어
          // (예: "Request contains an invalid argument") thinkingConfig는 빼고 maxOutputTokens만 넉넉히 준다.
          generationConfig: { maxOutputTokens: 2048 }
        })
      }
    );

    const data = await geminiRes.json();

    if (!geminiRes.ok) {
      return {
        statusCode: geminiRes.status,
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ error: (data && data.error && data.error.message) || "Gemini API 호출에 실패했어요." })
      };
    }

    const candidate = data.candidates && data.candidates[0];
    const rawAnswer =
      (candidate && candidate.content && candidate.content.parts && candidate.content.parts[0] && candidate.content.parts[0].text) ||
      "답변을 생성하지 못했어요. (안전 필터에 걸렸거나 응답이 비어있을 수 있어요)";

    // 답변 끝의 "[출처: ...]" / "[추천질문: ...]" 표기를 분리해서 각각 배열로 뽑아낸다.
    let answer = rawAnswer;
    let citations = [];
    let followups = [];

    const citeMatch = answer.match(/\[출처:\s*([^\]]+)\]/);
    if (citeMatch) {
      citations = citeMatch[1].split(/[|,]/).map(s => s.trim()).filter(Boolean);
      answer = answer.replace(citeMatch[0], "").trim();
    }
    const followMatch = answer.match(/\[추천질문:\s*([^\]]+)\]/);
    if (followMatch) {
      followups = followMatch[1].split(/[|,]/).map(s => s.trim()).filter(Boolean);
      answer = answer.replace(followMatch[0], "").trim();
    }

    return {
      statusCode: 200,
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ answer, citations, followups })
    };
  } catch (err) {
    return {
      statusCode: 500,
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ error: "서버 오류가 났어요: " + err.message })
    };
  }
};
